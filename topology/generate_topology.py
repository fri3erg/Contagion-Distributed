#!/usr/bin/env python3
"""Generate the fixed node topology and the matching docker-compose.yml.

The topology is fixed at startup (Spec sec. 9.1: "each node only knows its
direct neighbors, fixed at startup from a topology config"). This script
is the single source of truth for both files so they can never drift apart:
run it whenever you want to change node count, average degree, or any of
the tunable balance parameters in TUNABLES below, then `docker compose up`.

Algorithm: a Watts-Strogatz-style small-world graph (ring lattice + random
rewiring), which gives every node a handful of local neighbors plus a few
long-range shortcuts -- a reasonable, easy-to-reason-about stand-in for a
real peer-to-peer overlay. Connectivity is verified (and repaired, if
rewiring happened to disconnect something) before writing output.
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent

# Balance parameters (Spec sec. 14). Edit here, then re-run this script,
# to retune the game and regenerate docker-compose.yml in one step.
TUNABLES = {
    "TICK_MS": "250",
    "INCUBATION_MIN": "60",
    "INCUBATION_MAX": "180",
    "CURE_RUN_LENGTH": "5",
    "CURE_RUNS_FOR_100": "20",
    "RELAY_P_HEALTHY": "0.95",
    "RELAY_P_INFECTED": "0.30",
    "CURE_RUN_INTERVAL_MIN": "10",
    "CURE_RUN_INTERVAL_MAX": "20",
    "INFECT_P_BASELINE_MIN": "0.01",
    "INFECT_P_BASELINE_MAX": "0.02",
    "INFECT_P_TRUST_MIN": "0.15",
    "INFECT_P_TRUST_MAX": "0.25",
    "TRUST_THRESHOLD_DEFAULT": "0.5",
    "TRUST_INCREMENT_HEARTBEAT": "0.01",
    "TRUST_INCREMENT_SYNC": "0.05",
    "HIGH_TRUST_SYNC_PERIOD_TICKS": "4",
    "ALERT_TTL": "5",
    "ALERT_P_ON_ANOMALY": "0.6",
    "HEARTBEAT_PERIOD_TICKS": "1",
    "HEARTBEAT_ACK_TIMEOUT_S": "1.0",
}

CURE_RUNS_FOR_100 = int(TUNABLES["CURE_RUNS_FOR_100"])
SNIPE_BUDGET = "6"
CURE_BUDGET = "6"


def generate_graph(n: int, k: int, rewire_p: float, rng: random.Random) -> set[frozenset]:
    ids = list(range(n))
    edges: set[frozenset] = set()
    for i in ids:
        for j in range(1, k // 2 + 1):
            edges.add(frozenset((i, (i + j) % n)))

    for e in list(edges):
        if rng.random() >= rewire_p:
            continue
        a, b = tuple(e)
        candidates = [x for x in ids if x != a and frozenset((a, x)) not in edges]
        if not candidates:
            continue
        c = rng.choice(candidates)
        edges.discard(e)
        edges.add(frozenset((a, c)))

    _ensure_connected(n, edges, rng)
    return edges


def _ensure_connected(n: int, edges: set[frozenset], rng: random.Random) -> None:
    adj: dict[int, set[int]] = {i: set() for i in range(n)}
    for e in edges:
        a, b = tuple(e)
        adj[a].add(b)
        adj[b].add(a)

    def component_of(start: int) -> set[int]:
        seen = {start}
        stack = [start]
        while stack:
            cur = stack.pop()
            for nxt in adj[cur]:
                if nxt not in seen:
                    seen.add(nxt)
                    stack.append(nxt)
        return seen

    visited: set[int] = set()
    components: list[set[int]] = []
    for i in range(n):
        if i not in visited:
            comp = component_of(i)
            visited |= comp
            components.append(comp)

    # Bridge every extra component to the first one with a single edge.
    while len(components) > 1:
        a = rng.choice(list(components[0]))
        other = components.pop()
        b = rng.choice(list(other))
        edges.add(frozenset((a, b)))
        adj[a].add(b)
        adj[b].add(a)
        components[0] |= other


def build_topology(n: int, k: int, rewire_p: float, seed: int | None) -> dict:
    rng = random.Random(seed)
    edges = generate_graph(n, k, rewire_p, rng)
    ids = [f"node-{i:02d}" for i in range(n)]
    patient_zero = rng.choice(ids)

    nodes = [
        {"id": nid, "udp_port": 7000, "tcp_port": 7001, "control_port": 8000}
        for nid in ids
    ]
    edge_pairs = sorted(
        tuple(sorted((ids[a], ids[b]))) for a, b in (tuple(e) for e in edges)
    )
    return {
        "nodes": nodes,
        "edges": [list(e) for e in edge_pairs],
        "patient_zero": patient_zero,
        "generated_with": {"n": n, "k": k, "rewire_p": rewire_p, "seed": seed},
    }


def neighbors_of(topology: dict) -> dict[str, list[str]]:
    adj: dict[str, list[str]] = {n["id"]: [] for n in topology["nodes"]}
    for a, b in topology["edges"]:
        adj[a].append(b)
        adj[b].append(a)
    return adj


def render_compose(topology: dict) -> str:
    adj = neighbors_of(topology)
    lines: list[str] = []
    lines.append("# Generated by topology/generate_topology.py -- do not edit by hand.")
    lines.append("services:")

    lines.append("  aggregator:")
    lines.append("    build:")
    lines.append("      context: .")
    lines.append("      dockerfile: aggregator/Dockerfile")
    lines.append("    ports:")
    lines.append('      - "8000:8000"')
    lines.append("    environment:")
    lines.append(f'      CURE_RUNS_FOR_100: "{CURE_RUNS_FOR_100}"')
    lines.append(f'      SNIPE_BUDGET: "{SNIPE_BUDGET}"')
    lines.append(f'      CURE_BUDGET: "{CURE_BUDGET}"')
    lines.append("    restart: unless-stopped")
    lines.append("")

    for node in topology["nodes"]:
        nid = node["id"]
        peers = ",".join(adj[nid])
        is_pz = "true" if nid == topology["patient_zero"] else "false"
        lines.append(f"  {nid}:")
        lines.append("    build:")
        lines.append("      context: .")
        lines.append("      dockerfile: node/Dockerfile")
        lines.append("    environment:")
        lines.append(f'      NODE_ID: "{nid}"')
        lines.append(f'      PEERS: "{peers}"')
        lines.append(f'      PATIENT_ZERO: "{is_pz}"')
        lines.append('      AGGREGATOR_URL: "http://aggregator:8000"')
        for key, val in TUNABLES.items():
            lines.append(f'      {key}: "{val}"')
        lines.append("    depends_on:")
        lines.append("      - aggregator")
        lines.append("    restart: unless-stopped")
        lines.append("")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nodes", type=int, default=30)
    parser.add_argument("--degree", type=int, default=4, help="average node degree (even number)")
    parser.add_argument("--rewire-p", type=float, default=0.15)
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--topology-out", default=str(HERE / "topology.json"))
    parser.add_argument("--compose-out", default=str(REPO_ROOT / "docker-compose.yml"))
    args = parser.parse_args()

    topology = build_topology(args.nodes, args.degree, args.rewire_p, args.seed)

    Path(args.topology_out).write_text(json.dumps(topology, indent=2) + "\n", encoding="utf-8")
    Path(args.compose_out).write_text(render_compose(topology), encoding="utf-8")

    degrees = [len(v) for v in neighbors_of(topology).values()]
    print(f"wrote {args.topology_out} ({args.nodes} nodes, "
          f"avg degree {sum(degrees) / len(degrees):.2f}, patient zero {topology['patient_zero']})")
    print(f"wrote {args.compose_out}")


if __name__ == "__main__":
    main()
